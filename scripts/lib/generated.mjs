/**
 * The PHP arrays `npm run patterns:build` generates, so a request reads no
 * pattern file.
 *
 * inc/generated/patterns.php holds every pattern: its registration args, its
 * content with the assets URL token still in it, its section, layout and copy
 * rules, and the keys it binds through each binding source. It is built from
 * patterns/intents/*.json and patterns/*.html. inc/generated/icons.php holds
 * the icon map from assets/icons.json. inc/patterns.php and inc/icons.php
 * read them in place of the files.
 *
 * Each is a plain `return [ ... ];` with no expression in it, so OPcache keeps
 * the array in shared memory. They sit in inc/, which package.json `files`
 * ships and `npm run build` never cleans.
 *
 * scripts/build-patterns.mjs writes them, and with --check fails while either
 * differs from what this gives. scripts/check.mjs gives the same comparison
 * the stale copies in tests/invalid/generated/, which it must call stale.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { basename, join } from 'node:path';

export const INTENTS = join( 'patterns', 'intents' );
export const ICONS_JSON = join( 'assets', 'icons.json' );
export const GENERATED_PATTERNS = 'inc/generated/patterns.php';
export const GENERATED_ICONS = 'inc/generated/icons.php';
export const PREFIX = 'voyager-open/';

const PATTERNS_DOC = [
	'Generated by `npm run patterns:build` from patterns/intents/ and',
	'patterns/*.html. Do not edit it: edit an intent, run the build and commit',
	'this file with the markup.',
	'',
	'Pattern name => its registration args, with the assets URL token still in',
	'its content, its section, layout and copy rules, and the keys it binds',
	'through each binding source. It holds no expression, so OPcache keeps the',
	'array in memory and no request reads an intent or a markup file',
	'(inc/patterns.php).',
];

const ICONS_DOC = [
	'Generated by `npm run patterns:build` from assets/icons.json. Do not edit',
	'it: edit the icon set, run the build and commit this file.',
	'',
	'Icon name => SVG path data, read by Icons\\all() (inc/icons.php). It holds',
	'no expression, so OPcache keeps the array in memory.',
];

const isMap = ( value ) =>
	value !== null && typeof value === 'object' && ! Array.isArray( value );
const isStrings = ( value ) =>
	Array.isArray( value ) &&
	value.every( ( item ) => typeof item === 'string' );

/**
 * What an intent holds that the array cannot take as it is.
 *
 * inc/patterns.php passes the array to register_block_pattern() and returns
 * it from intent_meta() with no cast, so each field must already have the
 * type it is used as.
 *
 * @param {Object} meta A decoded intent file.
 * @return {string[]} Problems, none for an intent the array can hold.
 */
export function intentProblems( meta ) {
	const problems = [];
	// null is no value, as `??` reads it in register() and in the array.
	const optional = ( field, ok, type ) => {
		if (
			meta[ field ] !== undefined &&
			meta[ field ] !== null &&
			! ok( meta[ field ] )
		) {
			problems.push( `${ field } is not ${ type }` );
		}
	};

	if ( typeof meta.title !== 'string' || meta.title === '' ) {
		problems.push( 'title is not a string with text in it' );
	}
	optional(
		'description',
		( value ) => typeof value === 'string',
		'a string'
	);
	for ( const field of [ 'categories', 'keywords', 'blockTypes' ] ) {
		optional( field, isStrings, 'a list of strings' );
	}
	optional( 'viewportWidth', Number.isInteger, 'an integer' );
	optional( 'section', ( value ) => typeof value === 'string', 'a string' );
	optional( 'layout', ( value ) => typeof value === 'string', 'a string' );
	optional(
		'copy_rules',
		( value ) => isMap( value ) && Object.values( value ).every( isMap ),
		'an object of rule objects'
	);
	if ( ! isMap( meta.intent ) ) {
		problems.push( 'intent is not an object' );
	}

	return problems;
}

/**
 * The keys an intent tree binds through each source, at any depth, as
 * Patterns\keys_in() finds them: an object whose `source` is a string and
 * whose `args.key` is a string.
 *
 * @param {Object} tree The intent's `intent`, or any part of it.
 * @return {Object<string, string[]>} Source => its keys, each once, in the order first found.
 */
export function bindings( tree ) {
	const found = new Map();
	const walk = ( node ) => {
		if ( node === null || typeof node !== 'object' ) {
			return;
		}
		if (
			isMap( node ) &&
			typeof node.source === 'string' &&
			node.args !== null &&
			typeof node.args === 'object' &&
			typeof node.args.key === 'string'
		) {
			if ( ! found.has( node.source ) ) {
				found.set( node.source, new Set() );
			}
			found.get( node.source ).add( node.args.key );
		}
		for ( const child of Object.values( node ) ) {
			walk( child );
		}
	};
	walk( tree );

	return Object.fromEntries(
		[ ...found ].map( ( [ source, keys ] ) => [ source, [ ...keys ] ] )
	);
}

/**
 * One pattern's entry: what register() registers and what intent_meta() and
 * bound_keys() read, with the defaults register() always applied.
 *
 * @param {Object} meta   A decoded intent file, intentProblems() clean.
 * @param {string} markup Its patterns/<name>.html, the assets URL token kept.
 * @return {Object} The entry.
 */
export function patternEntry( meta, markup ) {
	return {
		args: {
			title: meta.title,
			description: meta.description ?? '',
			content: markup,
			categories: meta.categories ?? [ 'voyager-open' ],
			keywords: meta.keywords ?? [],
			blockTypes: meta.blockTypes ?? [],
			viewportWidth: meta.viewportWidth ?? 1280,
		},
		section: meta.section ?? null,
		layout: meta.layout ?? null,
		copy_rules: meta.copy_rules ?? {},
		bindings: bindings( meta.intent ),
	};
}

/**
 * A PHP single-quoted string literal. Only a backslash and a quote are
 * escaped there, so this reads back byte for byte.
 *
 * @param {string} text
 * @return {string} The literal.
 */
function quote( text ) {
	return `'${ text.replace( /[\\']/g, '\\$&' ) }'`;
}

/**
 * A JSON value as a PHP literal: objects become string-keyed arrays, as
 * json_decode( $json, true ) gives them. A list of scalars that fits on one
 * line stays on one line.
 *
 * @param {null|boolean|number|string|Array|Object} value A JSON value.
 * @param {number}                                  depth Indent level, in tabs.
 * @return {string} The literal.
 */
export function phpLiteral( value, depth = 0 ) {
	if ( value === null ) {
		return 'null';
	}
	if ( typeof value === 'boolean' ) {
		return value ? 'true' : 'false';
	}
	if ( typeof value === 'number' ) {
		if ( ! Number.isFinite( value ) ) {
			throw new Error( `${ value } has no PHP literal` );
		}
		return String( value );
	}
	if ( typeof value === 'string' ) {
		return quote( value );
	}
	if ( typeof value !== 'object' ) {
		throw new Error( `a ${ typeof value } has no PHP literal` );
	}

	const list = Array.isArray( value );
	const children = list ? value : Object.values( value );
	const items = list
		? value.map( ( item ) => phpLiteral( item, depth + 1 ) )
		: Object.entries( value ).map(
				( [ key, item ] ) =>
					`${ quote( key ) } => ${ phpLiteral( item, depth + 1 ) }`
			);

	if ( ! items.length ) {
		return '[]';
	}
	const inline = `[ ${ items.join( ', ' ) } ]`;
	if (
		list &&
		children.every(
			( item ) => item === null || typeof item !== 'object'
		) &&
		! inline.includes( '\n' ) &&
		inline.length <= 72
	) {
		return inline;
	}

	const pad = '\t'.repeat( depth + 1 );
	return `[\n${ items
		.map( ( item ) => `${ pad }${ item },\n` )
		.join( '' ) }${ '\t'.repeat( depth ) }]`;
}

/**
 * A generated file: a header, the direct-access guard every file in inc/
 * has, and `return <value>;`.
 *
 * @param {string[]}     doc   Lines of the header comment.
 * @param {Object|Array} value What the file returns.
 * @return {string} The file.
 */
function phpFile( doc, value ) {
	return [
		'<?php',
		'/**',
		...doc.map( ( line ) => ( line ? ` * ${ line }` : ' *' ) ),
		' *',
		' * @package VoyagerOpenBlocks',
		' */',
		'',
		'declare(strict_types=1);',
		'',
		"if ( ! defined( 'ABSPATH' ) ) {",
		'\texit;',
		'}',
		'',
		`return ${ phpLiteral( value ) };`,
		'',
	].join( '\n' );
}

/**
 * Both generated files, as they should be.
 *
 * Intents are read in the order glob() lists them, so patterns register in
 * the order they always have. A pattern with no markup is left out, as
 * register() always skipped it.
 *
 * @param {string}                        root      Repository root.
 * @param {(name: string) => string|null} markupFor A pattern's markup, or null when it has none.
 * @return {{files: {path: string, text: string, count: string}[], problems: string[]}} Each file's repository path, text and what it holds, and what kept a source out.
 */
export function generatedFiles( root, markupFor ) {
	const problems = [];
	const patterns = {};

	for ( const file of readdirSync( join( root, INTENTS ) )
		.filter( ( f ) => f.endsWith( '.json' ) )
		.sort() ) {
		const name = basename( file, '.json' );
		const meta = JSON.parse(
			readFileSync( join( root, INTENTS, file ), 'utf8' )
		);
		const invalid = intentProblems( meta );
		if ( invalid.length ) {
			problems.push(
				...invalid.map(
					( problem ) => `patterns/intents/${ file }: ${ problem }`
				)
			);
			continue;
		}
		const markup = markupFor( name );
		if ( typeof markup === 'string' ) {
			patterns[ PREFIX + name ] = patternEntry( meta, markup );
		}
	}

	const set = JSON.parse( readFileSync( join( root, ICONS_JSON ), 'utf8' ) );
	const icons = {};
	for ( const [ name, path ] of Object.entries(
		isMap( set?.icons ) ? set.icons : {}
	) ) {
		if ( typeof path === 'string' ) {
			icons[ name ] = path;
		} else {
			problems.push(
				`assets/icons.json: icon ${ name } is not a string`
			);
		}
	}
	if ( ! Object.keys( icons ).length ) {
		problems.push( 'assets/icons.json: no icons' );
	}

	return {
		files: [
			{
				path: GENERATED_PATTERNS,
				text: phpFile( PATTERNS_DOC, patterns ),
				count: `${ Object.keys( patterns ).length } patterns`,
			},
			{
				path: GENERATED_ICONS,
				text: phpFile( ICONS_DOC, icons ),
				count: `${ Object.keys( icons ).length } icons`,
			},
		],
		problems,
	};
}

/**
 * A pattern's committed markup, patterns/<name>.html, or null.
 *
 * @param {string} root Repository root.
 * @param {string} name Pattern name, without the prefix.
 * @return {string|null} The markup.
 */
export function committedMarkup( root, name ) {
	const file = join( root, 'patterns', `${ name }.html` );
	return existsSync( file ) ? readFileSync( file, 'utf8' ) : null;
}

/**
 * Whether a generated file on disk is stale: missing, or not byte for byte
 * the text it should hold. The one rule gate 1 and its control share.
 *
 * @param {string} text What the file should hold.
 * @param {string} file Path on disk.
 * @return {boolean} True when stale.
 */
export function isStale( text, file ) {
	return ! existsSync( file ) || readFileSync( file, 'utf8' ) !== text;
}
